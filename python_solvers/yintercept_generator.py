from pathlib import Path
from sympy import symbols, expand, solve, Eq, latex, Rational, simplify, gcd

# ── Globals ────────────────────────────────────────────────────────────

A, B, C, x, y = symbols('A B C x y')
PROJECT_ROOT = Path(__file__).parent.parent
DART_DIR = PROJECT_ROOT / "lib" / "midterm" / "solvers" / "yintercept_solver"
DART_DIR.mkdir(parents=True, exist_ok=True)

# ── SymPy Verification ─────────────────────────────────────────────────

def verify():
    print("=" * 60)
    print("SymPy Verification for y-intercept generator")
    print("=" * 60)

    # 1. Slope from standard form: Ax + By = C  -  y = (-A/B)x + C/B
    sol = solve(Eq(A*x + B*y, C), y)
    assert len(sol) == 1
    y_expr = sol[0]
    slope_coeff = expand(y_expr).coeff(x)
    intercept_const = expand(y_expr).subs(x, 0)
    print(f"  Ax + By = C  -  y = {latex(y_expr)}")
    print(f"    slope = {latex(slope_coeff)}  (expected -A/B)")
    print(f"    intercept = {latex(intercept_const)}  (expected C/B)")
    assert str(simplify(slope_coeff * B + A)) == "0", "Slope formula check failed"
    assert str(simplify(intercept_const * B - C)) == "0", "Intercept formula check failed"
    print("  [OK] Slope/intercept formulas verified\n")

    # 2. Perpendicular condition: m1 * m2 == -1
    m1, m2 = symbols('m1 m2')
    assert simplify(m1 * (-1/m1) + 1) == 0
    print("  [OK] Perpendicular: m1 x m2 = -1 verified\n")

    # 3. Test cases
    cases = [
        ((2, 3, 6), "y = (-2/3)x + 2"),
        ((3, -2, 12), "y = (3/2)x - 6"),
        ((5, 1, -10), "y = (-5)x - 10"),
        ((1, 1, 7), "y = (-1)x + 7"),
        ((0, 2, 8), "y = 4"),            # horizontal: A=0
    ]
    for (a_val, b_val, c_val), expected in cases:
        m_val = Rational(-a_val, b_val) if b_val != 0 else None
        b_int = Rational(c_val, b_val) if b_val != 0 else None
        status = "OK"
        print(f"  A={a_val}, B={b_val}, C={c_val}  ->  m={latex(m_val) if m_val else '0'}, "
              f"b={latex(b_int) if b_int else 'None'}")
        if b_val == 0:
            status = "vertical line"
        elif a_val == 0:
            status = "horizontal line"
        else:
            expected_m = Rational(-a_val, b_val)
            if not expected_m.equals(m_val):
                status = "FAIL"
        print(f"    {status}")

    # 4. Vertical line: B=0
    sol_v = solve(Eq(A*x, C), x)
    print(f"\n  Vertical line (B=0): {A}x = {C}  -  x = {latex(sol_v[0])}")

    # 5. Parallel / Perpendicular classification
    print("\n  Parallel test: m1 == m2 and b1 != b2")
    print("  Perpendicular test: m1 * m2 == -1")
    print("  Coincident test: m1 == m2 and b1 == b2\n")

    print("  [OK] All SymPy verifications passed\n")

